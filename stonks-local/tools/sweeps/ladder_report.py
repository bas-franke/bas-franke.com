"""Digest of the slice-sizing / indicator-ladder / multi-timeframe campaign -> stonks-local/LADDER.md.

    .venv/Scripts/python tools/sweeps/ladder_report.py [--out LADDER.md]

Reads data/lab.sqlite only (current eval version, current family versions). Rankings use the out-of-sample score;
holdout columns are reported, never used to pick. "worst DD" is the deepest drawdown in any of the 6 test folds, the
"big drop" number this campaign tries to shrink.
"""
from __future__ import annotations

import argparse
import json
import sqlite3
import statistics as st
import sys
import time
from collections import defaultdict
from pathlib import Path

LAB = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(LAB))

from stonks_lab.evaluate import EVAL_VERSION  # noqa: E402
from stonks_lab.families import FAMILIES, INTERVALS  # noqa: E402

OWN = ["ind_ladder_a24", "step_wrap_a24", "mtf_guard_a24"]


def load(db, where="", args=()):
    q = ("select spec_hash, family, family_version, interval, markets, params, score, metrics, holdout from experiments"
         " where status='done' and score is not null " + where)
    out = []
    for h, fam, fv, iv, mk, params, score, metrics, holdout in db.execute(q, args):
        m = json.loads(metrics or "{}")
        sp = m.get("scoreParts") or {}
        if sp.get("evalVersion", m.get("evalVersion")) != EVAL_VERSION:
            continue
        f = FAMILIES.get(fam)
        if f is not None and (fv or 1) < f.invalid_below:
            continue
        folds = m.get("folds") or []
        dds = [fd["test"]["maxDrawdownPct"] for fd in folds if fd.get("test")]
        ho = json.loads(holdout or "{}")
        out.append({"hash": h[:10], "family": fam, "iv": iv, "mk": mk, "p": json.loads(params), "score": score,
                    "eligible": bool(sp.get("eligible")), "trades": sp.get("testTrades") or 0,
                    "medDD": sp.get("medianDrawdownPct"), "worstDD": max(dds) if dds else None,
                    "expo": sp.get("medianExposurePct"), "beat": sp.get("foldsBeatBuyHold"),
                    "hoRet": ho.get("returnPct"), "hoVs": ho.get("vsBuyHoldPct"), "hoDD": ho.get("maxDrawdownPct")})
    return out


def f1(x, nd=1):
    return "" if x is None else f"{x:.{nd}f}"


def short(p, drop=("inner",)):
    s = json.dumps({k: v for k, v in p.items() if k not in drop}, separators=(",", ":"))
    return s if len(s) <= 110 else s[:107] + "..."


def table(rows, cols):
    head = "| " + " | ".join(c for c, _ in cols) + " |\n|" + "---|" * len(cols) + "\n"
    return head + "".join("| " + " | ".join(str(fn(r)) for _, fn in cols) + " |\n" for r in rows)


BASE_COLS = [("hash", lambda r: f"`{r['hash']}`"), ("family", lambda r: r["family"]), ("iv", lambda r: r["iv"]),
             ("market", lambda r: r["mk"].split("-")[0]), ("score", lambda r: f1(r["score"])),
             ("med DD", lambda r: f1(r["medDD"])), ("worst DD", lambda r: f1(r["worstDD"])),
             ("expo", lambda r: f1(r["expo"], 0)), ("trades", lambda r: r["trades"]),
             ("holdout %", lambda r: f1(r["hoRet"])), ("vs B&H", lambda r: f1(r["hoVs"])),
             ("holdout DD", lambda r: f1(r["hoDD"]))]


def ranked(rows):
    return sorted((r for r in rows if r["eligible"] and r["trades"] >= 5), key=lambda r: -r["score"])


def med(xs):
    xs = [x for x in xs if x is not None]
    return st.median(xs) if xs else None


def group_stats(rows, key):
    g = defaultdict(list)
    for r in rows:
        g[key(r)].append(r)
    return g


def lead_score(db, fam, params, iv, mk):
    for r in load(db, "and family=? and interval=? and markets=?", (fam, iv, mk)):
        if r["p"] == params:
            return r
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(LAB / "LADDER.md"))
    a = ap.parse_args()
    db = sqlite3.connect(LAB / "data" / "lab.sqlite")
    rows = {f: load(db, "and family=?", (f,)) for f in OWN}
    hold = {"BTC-EUR": None, "ETH-EUR": None}
    L = [f"# Slice sizing, TAAPI indicator ladder and multi-timeframe guards\n\nGenerated by "
         f"`tools/sweeps/ladder_report.py` on {time.strftime('%Y-%m-%d %H:%M')} (eval v{EVAL_VERSION}). Campaign: "
         "`tools/sweeps/ladder_campaign.py`. Score = out-of-sample excess log return over buy and hold minus half "
         "the median fold drawdown (RESEARCH.md); buy and hold itself scores about -17 (BTC) / -25 (ETH), so a "
         "score above that beats holding. **worst DD** = deepest drawdown in any test fold (%), the 'big drop' "
         "number. Holdout (last 365 days) is reported, never used for picking.\n"]
    L.append("| family | experiments | eligible |\n|---|---|---|\n" + "".join(
        f"| {f} | {len(rs)} | {sum(r['eligible'] for r in rs)} |\n" for f, rs in rows.items()))

    allr = [r for rs in rows.values() for r in rs]
    L.append("\n## Best 20 of the campaign\n\n" + table(ranked(allr)[:20], BASE_COLS + [
        ("params", lambda r: f"`{short(r['p'])}`" + (f" inner `{r['p']['inner']['family']}`" if "inner" in r["p"] else ""))]))

    calm = [r for r in ranked(allr) if r["worstDD"] is not None and r["worstDD"] <= 25]
    L.append("\n## Small drops only (worst test-fold drawdown <= 25 %)\n\n" + table(calm[:15], BASE_COLS + [
        ("params", lambda r: f"`{short(r['p'])}`" + (f" inner `{r['p']['inner']['family']}`" if "inner" in r["p"] else ""))]))

    lad = rows["ind_ladder_a24"]
    if lad:
        L.append("\n## Indicator ladder per interval\n\nBest eligible score per interval and market (n = specs "
                 "tried), and the median of all specs.\n\n| interval | BTC best | BTC median | BTC n | ETH best | "
                 "ETH median | ETH n | best BTC spec |\n|---|---|---|---|---|---|---|---|\n")
        for iv in INTERVALS:
            cells = []
            best_spec = ""
            for mk in ("BTC-EUR", "ETH-EUR"):
                rs = [r for r in lad if r["iv"] == iv and r["mk"] == mk]
                rk = ranked(rs)
                cells += [f1(rk[0]["score"]) if rk else "", f1(med([r["score"] for r in rs])), len(rs)]
                if mk == "BTC-EUR" and rk:
                    best_spec = f"`{rk[0]['hash']}` {rk[0]['p']['indicator']}/{rk[0]['p']['mode']}"
            if any(cells[i] for i in (2, 5)):
                L.append(f"| {iv} | " + " | ".join(map(str, cells)) + f" | {best_spec} |\n")

        L.append("\n## Indicators compared\n\nOver every interval and both markets: best eligible score, the median "
                 "of each indicator's best-per-cell score (cell = interval x market), and its best mode.\n\n"
                 "| indicator | best | median cell best | cells beating hold | best mode | n |\n|---|---|---|---|---|---|\n")
        by_ind = group_stats(lad, lambda r: r["p"]["indicator"])
        lines = []
        for ind_name, rs in by_ind.items():
            cell_best = {}
            for r in ranked(rs):
                cell_best.setdefault((r["iv"], r["mk"]), r)
            cb = list(cell_best.values())
            beat = sum(1 for r in cb if r["score"] > (-17 if r["mk"] == "BTC-EUR" else -25))
            modes = group_stats(ranked(rs)[:30], lambda r: r["p"]["mode"])
            bm = max(modes, key=lambda k: len(modes[k])) if modes else ""
            best = ranked(rs)[0]["score"] if ranked(rs) else None
            lines.append((best if best is not None else -1e9,
                          f"| {ind_name} | {f1(best)} | {f1(med([r['score'] for r in cb]))} | {beat}/{len(cb)} | {bm} | {len(rs)} |\n"))
        L += [ln for _, ln in sorted(lines, reverse=True)]

        L.append("\n## Slice size (all ladder specs)\n\n| step | n | median score | median of top 10 % | median worst DD "
                 "|\n|---|---|---|---|---|\n")
        for stp, rs in sorted(group_stats(lad, lambda r: r["p"]["step"]).items()):
            sc = sorted((r["score"] for r in rs), reverse=True)
            top = sc[: max(1, len(sc) // 10)]
            L.append(f"| {stp} | {len(rs)} | {f1(med(sc))} | {f1(med(top))} | {f1(med([r['worstDD'] for r in rs]))} |\n")

        L.append("\n## Drawdown guards (ladder)\n\n| guard | n | median score | median of top 10 % | median worst DD "
                 "|\n|---|---|---|---|---|\n")

        def gk(r):
            p = r["p"]
            g = [n for n, on in (("trend SMA", p.get("trendSma")), ("drawdown", p.get("ddLook"))) if on]
            return (" + ".join(g) or "none") + (" (sell all)" if g and p.get("guardExit") else "")
        for k, rs in sorted(group_stats(lad, gk).items()):
            sc = sorted((r["score"] for r in rs), reverse=True)
            L.append(f"| {k} | {len(rs)} | {f1(med(sc))} | {f1(med(sc[: max(1, len(sc) // 10)]))} | "
                     f"{f1(med([r['worstDD'] for r in rs]))} |\n")

    sw = rows["step_wrap_a24"]
    if sw:
        L.append("\n## Existing leads traded in slices (step_wrap_a24)\n\nLead = the original spec. '10 %' = the "
                 "same lead bought and sold 10 % of the portfolio per bar, no guards. 'best' = best wrapped variant "
                 "(any slice, pace, guard) by score.\n\n| lead | iv | market | lead score | lead worst DD | 10 % "
                 "score | 10 % worst DD | best score | best worst DD | best params |\n|---|---|---|---|---|---|---|---|---|---|\n")
        g = group_stats(sw, lambda r: (json.dumps(r["p"]["inner"], sort_keys=True), r["iv"], r["mk"]))
        for (inner_s, iv, mk), rs in sorted(g.items(), key=lambda kv: -max(r["score"] for r in kv[1])):
            inner = json.loads(inner_s)
            base = lead_score(db, inner["family"], inner["params"], iv, mk)
            ten = next((r for r in rs if r["p"]["step"] == 0.1 and r["p"]["every"] == 1 and not r["p"].get("trendSma")
                        and not r["p"].get("ddLook")), None)
            best = max(rs, key=lambda r: r["score"])
            L.append(f"| {inner['family']} | {iv} | {mk.split('-')[0]} | {f1(base and base['score'])} | "
                     f"{f1(base and base['worstDD'])} | {f1(ten and ten['score'])} | {f1(ten and ten['worstDD'])} | "
                     f"{f1(best['score'])} | {f1(best['worstDD'])} | `{short(best['p'])}` |\n")

    mg = rows["mtf_guard_a24"]
    if mg:
        L.append("\n## Multi-timeframe: slow lead + fast crash guard (mtf_guard_a24)\n\n'no guard' = the lead on its "
                 "own time frame, traded on the faster candles. 'best guard' = best guarded variant by score.\n\n"
                 "| lead | lead tf | trade tf | market | no guard score | no guard worst DD | best guard score | "
                 "best worst DD | guard |\n|---|---|---|---|---|---|---|---|---|\n")
        g = group_stats(mg, lambda r: (r["p"]["inner"]["family"], json.dumps(r["p"]["inner"]["params"], sort_keys=True),
                                       r["p"]["leadTf"], r["iv"], r["mk"]))
        for (fam, _, ltf, iv, mk), rs in sorted(g.items(), key=lambda kv: -max(r["score"] for r in kv[1])):
            base = next((r for r in rs if not r["p"].get("guardLook")), None)
            gd = [r for r in rs if r["p"].get("guardLook")]
            if not gd:
                continue
            b = max(gd, key=lambda r: r["score"])
            gp = b["p"]
            gtxt = (f"{gp['guardTf']} {gp['guardLook']} bars, -{gp['guardDrop'] * 100:.0f} %, cut {gp['guardCut']}, "
                    f"hold {gp['guardHold']}, step {gp['step']}")
            L.append(f"| {fam} | {ltf} | {iv} | {mk.split('-')[0]} | {f1(base and base['score'])} | "
                     f"{f1(base and base['worstDD'])} | {f1(b['score'])} | {f1(b['worstDD'])} | {gtxt} |\n")
    Path(a.out).write_text("".join(L), encoding="utf8")
    print(f"wrote {a.out}: {sum(len(r) for r in rows.values())} experiments")


if __name__ == "__main__":
    main()
