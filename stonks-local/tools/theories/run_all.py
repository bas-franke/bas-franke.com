"""Run every theory (tNN_*.py) and write out/theories/index.html plus THEORIES.md (the committed summary).

    .venv/Scripts/python tools/theories/run_all.py             # all, with walk-forward scores
    .venv/Scripts/python tools/theories/run_all.py --fast t02  # only names containing t02, no walk-forward
"""
from __future__ import annotations

import argparse
import datetime as dt
import html
import importlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from _harness import LAB_DIR, OUT_DIR, run  # noqa: E402

WORD = {True: "supported", False: "rejected", None: "inconclusive"}


def _f(x, d=1):
    return "–" if x is None else f"{x:,.{d}f}"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("only", nargs="*", help="substrings of theory file names to run")
    ap.add_argument("--fast", action="store_true", help="skip the walk-forward evaluation")
    a = ap.parse_args(argv)
    files = sorted(p for p in HERE.glob("t[0-9][0-9]_*.py") if not a.only or any(s in p.stem for s in a.only))
    summaries = []
    for p in files:
        print(f"\n=== {p.stem}")
        th = importlib.import_module(p.stem).THEORY
        summaries.append(run(th, ["--quiet"] + (["--fast"] if a.fast else [])))
    rows = "".join(f"<tr><td><a href='{s['theory']}/index.html'>{s['theory']}</a></td><td>{WORD[s['verdict']]}</td>"
                   f"<td>{html.escape(s['hypothesis'])}</td><td>{html.escape(s['why'])}</td></tr>" for s in summaries)
    (OUT_DIR / "index.html").write_text(
        "<!doctype html><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'>"
        "<title>Theories</title><style>body{font:14px/1.5 system-ui;max-width:1200px;margin:auto;padding:20px 16px}"
        "td,th{padding:6px;border-bottom:1px solid #ddd;vertical-align:top;text-align:left}"
        "@media (prefers-color-scheme:dark){body{background:#161615;color:#ecebe7}a{color:#7aa2ff}}</style>"
        f"<h1>Theories</h1><table><tr><th>theory</th><th>verdict</th><th>hypothesis</th><th>evidence</th></tr>{rows}"
        "</table>", encoding="utf-8")
    if not a.only:
        md = [f"# Theories\n\nGenerated by `tools/theories/run_all.py` on {dt.date.today()}: full history, fees and "
              "fills per SPEC §2, EUR 1000 start. The full-history numbers are in-sample; `OOS score` is the lab's "
              "walk-forward score (same as `lab.py top`). Charts with every buy and sell: `out/theories/<theory>/` "
              "(local, git-ignored), or `tools/trade_chart.py` for any spec.\n",
              "| theory | verdict | hypothesis | evidence |", "|---|---|---|---|"]
        md += [f"| `{s['theory']}` | **{WORD[s['verdict']]}** | {s['hypothesis']} | {s['why']} |" for s in summaries]
        md.append("\n## Variants\n")
        for s in summaries:
            md.append(f"### {s['theory']}\n\n| variant | return | B&H | max DD | Sharpe | buys/sells | win | fees "
                      "| OOS score |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|")
            for k, r in s["variants"].items():
                if "error" in r:
                    md.append(f"| {k} | error: {r['error']} | | | | | | | |")
                    continue
                m, b = r["metrics"], r["buyHold"]
                md.append(f"| {k} | {_f(m['returnPct'])} % | {_f(b['returnPct'])} % | {_f(m['maxDrawdownPct'])} % | "
                          f"{_f(m['sharpe'], 2)} | {m['buys']}/{m['sells']} | {_f(m['winRatePct'])} % | "
                          f"€{_f(m['feesEur'], 0)} | {_f(r.get('score'), 2)} |")
            md.append("")
        (LAB_DIR / "THEORIES.md").write_text("\n".join(md), encoding="utf-8")
    print(f"\nall theories: {OUT_DIR / 'index.html'}")


if __name__ == "__main__":
    main()
